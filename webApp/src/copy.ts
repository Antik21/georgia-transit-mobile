export function getLanguage(languageTag: string): Language {
  const language = languageTag.toLowerCase().split("-")[0];
  return language === "ru" || language === "ka" ? language : "en";
}

export function getCopy(languageTag: string): Copy {
  return translations[getLanguage(languageTag)];
}
